static int glyph_index(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a';
    if (c >= '0' && c <= '9') return 26 + (c - '0');
    switch (c) {
        case ':': return 36; case '.': return 37;
        case '-': return 38; case '_': return 39;
        case '/': return 40; case ' ': return 41;
        default:  return 41;
    }
}

static inline uint32_t pack(Color c) {
    return ((uint32_t)c.a << 24) | ((uint32_t)c.r << 16) |
           ((uint32_t)c.g << 8)  |  (uint32_t)c.b;
}

static inline void put_px(int x, int y, uint32_t px) {
    if (x < 0 || y < 0 || x >= SCREEN_W || y >= SCREEN_H) return;
    uint32_t *fb = (uint32_t *)g_fb[g_fb_idx];
    fb[y * (g_pitch / 4) + x] = px;
}

int gfx_init(void) {
    videoState state;
    if (videoGetState(0, 0, &state) != 0) return -1;
    if (videoGetResolution(state.displayMode.resolution, &g_vcfg) != 0) return -1;
    g_vcfg.aspect = VIDEO_ASPECT_16_9;
    if (videoConfigure(0, &g_vcfg, NULL, 0) != 0) return -1;

    int w = g_vcfg.width, h = g_vcfg.height;
    g_pitch = w * 4;
    for (int i = 0; i < 2; i++) {
        g_fb[i] = rsxMemalign(64, g_pitch * h);
        memset(g_fb[i], 0, g_pitch * h);
    }
    return 0;
}

void gfx_shutdown(void) {
    for (int i = 0; i < 2; i++) if (g_fb[i]) rsxFree(g_fb[i]);
}

void gfx_begin(void) { }

void gfx_end(void) {
    gcmSetDisplayBuffer(g_fb_idx, (uint32_t)(uintptr_t)g_fb[g_fb_idx],
                        g_pitch, g_vcfg.width, g_vcfg.height);
    g_fb_idx ^= 1;
}

void gfx_clear(Color c) {
    uint32_t px = pack(c);
    uint32_t *fb = (uint32_t *)g_fb[g_fb_idx];
    int n = g_pitch * g_vcfg.height / 4;
    for (int i = 0; i < n; i++) fb[i] = px;
}

void gfx_rect(int x, int y, int w, int h, Color c) {
    uint32_t px = pack(c);
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++) put_px(x + i, y + j, px);
}

void gfx_text(int x, int y, const char *s, Color c, int scale) {
    uint32_t px = pack(c);
    int cx = x;
    for (const char *p = s; *p; p++) {
        int gi = glyph_index(*p);
        for (int row = 0; row < 7; row++) {
            uint8_t bits = FONT[gi][row];
            for (int col = 0; col < 5; col++) {
                if (bits & (1 << (4 - col))) {
                    for (int sy = 0; sy < scale; sy++)
                        for (int sx = 0; sx < scale; sx++)
                            put_px(cx + col * scale + sx, y + row * scale + sy, px);
                }
            }
        }
        cx += 6 * scale;
    }
}

int gfx_text_width(const char *s, int scale) {
    int n = 0; while (*s++) n++;
    return n * 6 * scale;
}

void gfx_draw_image(const Image *img, int x, int y, int w, int h) {
    if (!img || !img->px) return;
    for (int j = 0; j < h; j++) {
        int sy = (int)((long)j * img->h / h);
        for (int i = 0; i < w; i++) {
            int sx = (int)((long)i * img->w / w);
            put_px(x + i, y + j, img->px[sy * img->w + sx]);
        }
    }
}

void gfx_draw_image_centered(const Image *img) {
    if (!img) return;
    int w = img->w, h = img->h;
    if (w > SCREEN_W) { h = h * SCREEN_W / w; w = SCREEN_W; }
    if (h > SCREEN_H) { w = w * SCREEN_H / h; h = SCREEN_H; }
    gfx_draw_image(img, (SCREEN_W - w) / 2, (SCREEN_H - h) / 2, w, h);
}

void gfx_free_image(Image *img) {
    if (!img) return;
    if (img->px) free(img->px);
    free(img);
}
